package Loops;
import java.util.Scanner;
public class LoopsBasics {
  public   static void main(String[] args) {
        Scanner sc = new Scanner(System.in);
        System.out.print("Enter N :");
        int N = sc.nextInt();
        for(int i=1;i<=N;i++){
                System.out.println(" hello ");
        }
    }
}
