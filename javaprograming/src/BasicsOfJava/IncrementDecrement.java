package BasicsOfJava;

public class IncrementDecrement {
    static void main() {
        int x = 5;
        System.out.println(x);
        x++;// this is post increment sirf increment hoga print toh x ayega updated value ..
        System.out.println(x);
        ++x; // this is preincrement phele increment hoga print karoge toh updated value print hogi..
        System.out.println(x);
        --x;
        System.out.println(x);
        x--;
        System.out.println(x);
    }
}
